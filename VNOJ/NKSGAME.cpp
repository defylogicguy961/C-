void solve()
{
    int n;
    cin >> n;
    vector<int> a(n);
    for (int i = 0; i < n; i++)
        cin >> a[i];
    sort(all(a));
    int ans = LLONG_MAX;
    for (int i = 0, x; i < n; i++)
    {
        cin >> x;
        auto it = lower_bound(all(a), -x);
        if (it != a.end())
            ans = min(ans, abs(*it + x));
        if (it != a.begin())
            ans = min(ans, abs(*prev(it) + x));
    }
    cout << ans;
}

