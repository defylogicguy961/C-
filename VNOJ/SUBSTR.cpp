void solve()
{
    string a, b;
    cin >> b >> a;
    int n = a.size();
    vector<int> pi(n, 0);
    for (int i = 1; i < n; i++)
    {
        int j = pi[i - 1];
        while (j > 0 and a[i] != a[j])
            j = pi[j - 1];
        if (a[i] == a[j])
            j++;
        pi[i] = j;
    }
    int j = 0;
    for (int i = 0; i < b.size(); i++)
    {
        while (j > 0 and (j == n or b[i] != a[j]))
            j = pi[j - 1];
        if (b[i] == a[j])
            j++;
        if (j == n)
        {
            cout << i - n + 2 << ' ';
            j = pi[n - 1];
        }
    }
}

